import bpy

from pxr import Tf
from mathutils import Matrix
from exporter.monke_logging import get_logger


logger = get_logger(__name__)
ASSETS_COLLECTION_NAME = "assets"
# GN evaluates points in float32, so a point empty's matrix and the instance matrix
# differ by more than float64 noise - compare relative to the value's magnitude
MATRIX_MATCH_TOLERANCE = 1e-4


class InstancerItem:
    """
    one asset placement generated by a Geometry Nodes instancer.
    instancer_name: name of the object carrying the GN modifier that generated it
    point_name: name of the empty that defines the instance point (read into GN with
                Collection Info / Object Info), None when no empty matches
    transform: (location, rotation_quaternion, scale) of the whole asset, from Matrix.decompose().
               It maps the asset as authored in its own file (meshes at their source
               matrix_world) onto this placement, so it can go straight onto the referencing prim.
    """
    def __init__(self, asset_name: str, instancer_name: str, point_name: str | None, transform):
        self.asset_name = asset_name
        self.instancer_name = instancer_name
        self.point_name = point_name
        self.transform = transform

    def __repr__(self):
        rot, loc, scale = self.decompose_transform()
        return (
            f"{self.asset_name} instance from {self.instancer_name} at point {self.point_name}, "
            f"position: {loc}, rotation {rot}, scale: {scale}"
        )

    def decompose_transform(self, rotation_mode="EULER"):
        loc, rot_quat, scale = self.transform
        rot = rot_quat.to_euler('XYZ') if rotation_mode == 'EULER' else rot_quat
        return rot, loc, scale


class SceneCollector:
    """shared helpers for collectors that read scene objects outside the assets tree"""

    def __init__(self, context=None):
        self.context = context or bpy.context
        # collection paths are looked up per depsgraph instance, which can run into
        # thousands, so the outliner walk is cached per object for one collect() call
        self._collection_paths_cache = {}

    def get_object_collection_paths(self, obj: bpy.types.Object) -> list[str]:
        """
        outliner paths ('assets/robot/arm') of every collection that links obj directly,
        relative to the scene collection
        """
        cached = self._collection_paths_cache.get(obj.name)
        if cached is not None:
            return cached

        target_collections = set(obj.users_collection)
        paths = []

        def walk(collection, current_path):
            for child in collection.children:
                child_path = current_path + [child.name]
                if child in target_collections:
                    paths.append("/".join(child_path))
                walk(child, child_path)

        walk(self.context.scene.collection, [])
        self._collection_paths_cache[obj.name] = paths
        return paths

    def get_asset_name(self, obj: bpy.types.Object) -> str | None:
        for collection_path in self.get_object_collection_paths(obj):
            parts = collection_path.split("/")
            if parts[0] == ASSETS_COLLECTION_NAME and len(parts) > 1:
                return parts[1]
        return None


class WorldCollector(SceneCollector):
    """
    collects Geometry Nodes instancers (objects with an empty base geometry and a
    GN modifier) and the asset placements they generate, with world-space transforms.
    instances_dict: {instancer_collection_path: [InstancerItem]}
    """

    def __init__(self, context=None):
        super().__init__(context)
        self.instances_dict = {}

    @staticmethod
    def has_geonodes_modifier(obj: bpy.types.Object) -> bool:
        return any(mod.type == 'NODES' and mod.show_viewport for mod in obj.modifiers)

    @staticmethod
    def is_empty_geometry(obj: bpy.types.Object) -> bool:
        """
        zero base vertices/splines - the usual container setup for Geometry Nodes
        """
        if obj.type == 'EMPTY':
            return True
        if obj.type == 'MESH' and obj.data:
            return len(obj.data.vertices) == 0
        if obj.type == 'CURVE' and obj.data:
            return len(obj.data.splines) == 0
        return False

    def get_target_containers(self, only_empty_geo: bool = True) -> set:
        return {
            obj.name
            for obj in self.context.scene.objects
            if self.has_geonodes_modifier(obj) and (not only_empty_geo or self.is_empty_geometry(obj))
        }

    def get_point_empties(self, target_containers: set) -> list[tuple[str, Matrix]]:
        """
        empties outside the assets tree that may define instance points. Empties inside
        assets (e.g. the robot's joint empties) are instanced along with the asset and
        would match their own instances, so they are left out, as are the instancers.
        """
        return [
            (obj.name, obj.matrix_world.copy())
            for obj in self.context.scene.objects
            if obj.type == 'EMPTY'
            and obj.name not in target_containers
            and self.get_asset_name(obj) is None
        ]

    @staticmethod
    def get_asset_matrix(instance_matrix: Matrix, source_obj: bpy.types.Object, asset_name: str | None) -> Matrix:
        """
        every mesh of a collection instance gets instance_point @ T(-instance_offset) @ mesh_matrix,
        so removing the mesh's own matrix and the collection offset gives the same point
        matrix for all meshes of one placement
        """
        asset_matrix = instance_matrix @ source_obj.matrix_world.inverted_safe()
        asset_collection = bpy.data.collections.get(asset_name) if asset_name else None
        if asset_collection is not None:
            asset_matrix = asset_matrix @ Matrix.Translation(asset_collection.instance_offset)
        return asset_matrix

    @staticmethod
    def matrices_match(a: Matrix, b: Matrix) -> bool:
        return all(
            abs(va - vb) <= MATRIX_MATCH_TOLERANCE * max(1.0, abs(va), abs(vb))
            for row_a, row_b in zip(a, b)
            for va, vb in zip(row_a, row_b)
        )

    def find_point_name(self, asset_matrix: Matrix, point_empties: list[tuple[str, Matrix]]) -> str | None:
        """
        GN's Instances to Points drops object identity, so the empty behind an instance
        point can only be recovered by matching its world matrix
        """
        for name, matrix in point_empties:
            if self.matrices_match(asset_matrix, matrix):
                return Tf.MakeValidIdentifier(name)
        return None

    @staticmethod
    def placement_key(asset_matrix: Matrix) -> tuple:
        # rounded so the float32 jitter between meshes of one placement collapses to one key
        return tuple(round(value, 3) for row in asset_matrix for value in row)

    def collect(self, only_empty_geo: bool = True, source_collections: list[str] | None = None) -> dict:
        """
        only_empty_geo: only use GN containers with no base vertices/splines
        source_collections: collection names the instanced meshes must belong to,
                            None accepts any collection
        returns instances_dict
        """
        self.instances_dict = {}
        self._collection_paths_cache = {}

        target_containers = self.get_target_containers(only_empty_geo=only_empty_geo)
        if not target_containers:
            return self.instances_dict

        allowed_collections = set(source_collections) if source_collections else None
        point_empties = self.get_point_empties(target_containers)
        depsgraph = self.context.evaluated_depsgraph_get()
        # one placement shows up once per mesh of the asset, dedupe them into one item
        seen_placements = set()

        for inst in depsgraph.object_instances:
            if not inst.is_instance:
                continue

            parent = inst.parent
            if not parent or parent.original.name not in target_containers:
                continue

            # inst.object.original is the source mesh inside the instanced collection
            source_obj = inst.object.original
            if source_obj.type != 'MESH':
                continue

            if allowed_collections is not None and not any(
                col.name in allowed_collections for col in source_obj.users_collection
            ):
                continue

            instancer = parent.original
            instancer_paths = self.get_object_collection_paths(instancer)
            if not instancer_paths:
                logger.warning(f"Instancer {instancer.name} is not in any collection, skipping")
                continue

            asset_name = self.get_asset_name(source_obj)
            if asset_name is None:
                logger.warning(f"{source_obj.name} instanced by {instancer.name} is not under an asset collection")

            asset_matrix = self.get_asset_matrix(inst.matrix_world, source_obj, asset_name)
            key = (instancer.name, asset_name, self.placement_key(asset_matrix))
            if key in seen_placements:
                continue
            seen_placements.add(key)

            point_name = self.find_point_name(asset_matrix, point_empties)
            # asset_matrix includes the collection instance_offset so it lines up with the
            # point empty, but the asset file authors its meshes at their plain matrix_world
            # with no offset, so the reference needs the transform without it
            placement_matrix = inst.matrix_world @ source_obj.matrix_world.inverted_safe()
            self.instances_dict.setdefault(instancer_paths[0], []).append(
                InstancerItem(asset_name, instancer.name, point_name, placement_matrix.decompose())
            )

        return self.instances_dict


class LightItem:
    """
    snapshot of one Blender light object with the values UsdLux can reproduce.
    collection_path: outliner path of its collection ('' for the scene collection)
    matrix_world: world matrix of the light object, lights shine along their local -Z in both apps
    """
    def __init__(self, obj: bpy.types.Object, collection_path: str):
        light = obj.data
        self.name = obj.name
        self.collection_path = collection_path
        self.matrix_world = obj.matrix_world.copy()
        self.light_type = light.type
        self.color = tuple(light.color)
        self.energy = light.energy
        self.exposure = getattr(light, "exposure", 0.0)
        self.use_temperature = getattr(light, "use_temperature", False)
        self.temperature = getattr(light, "temperature", 6500.0)
        self.use_shadow = light.use_shadow
        self.diffuse_factor = light.diffuse_factor
        self.specular_factor = light.specular_factor
        # type specific, None when the light type doesn't have it
        self.radius = getattr(light, "shadow_soft_size", None)
        self.spot_size = getattr(light, "spot_size", None)
        self.spot_blend = getattr(light, "spot_blend", None)
        self.angle = getattr(light, "angle", None)
        self.shape = getattr(light, "shape", None)
        self.size = getattr(light, "size", None)
        self.size_y = getattr(light, "size_y", None)

    def __repr__(self):
        return f"{self.light_type} light {self.name} in '{self.collection_path}'"


class LightsCollector(SceneCollector):
    """
    collects light objects outside the assets tree that UsdLux can reproduce.
    items: [LightItem]
    """
    SUPPORTED_TYPES = {"POINT", "SPOT", "SUN", "AREA"}

    def __init__(self, context=None):
        super().__init__(context)
        self.items = []

    def is_reproducible(self, obj: bpy.types.Object) -> bool:
        light = obj.data
        if light.type not in self.SUPPORTED_TYPES:
            logger.warning(f"Skipping light {obj.name}: {light.type} lights have no UsdLux equivalent")
            return False
        # UsdLux has no ellipse light, a DiskLight only covers the round case
        if light.type == "AREA" and light.shape == "ELLIPSE" and abs(light.size - light.size_y) > 1e-6:
            logger.warning(f"Skipping light {obj.name}: UsdLux has no ellipse light, use a disk or rectangle")
            return False
        return True

    def collect(self) -> list[LightItem]:
        self.items = []
        self._collection_paths_cache = {}

        for obj in self.context.scene.objects:
            if obj.type != 'LIGHT' or obj.hide_render:
                continue
            if self.get_asset_name(obj) is not None:
                logger.warning(f"Skipping light {obj.name}: lights inside assets aren't exported yet")
                continue
            if not self.is_reproducible(obj):
                continue

            collection_paths = self.get_object_collection_paths(obj)
            self.items.append(LightItem(obj, collection_paths[0] if collection_paths else ""))

        return self.items


