from pxr import Gf, Kind, Sdf, UsdGeom
from exporter.collectors.collector_assets import VARIANT_SEPARATOR


FPS = 30
DEFORM_MODIFIER_TYPES = {"ARMATURE", "CLOTH", "SOFT_BODY", "SURFACE_DEFORM"}
MAX_JOINT_INFLUENCES = 4
LOD_VARIANT_SET = "lod"
LOD_PURPOSES = {
    "render": UsdGeom.Tokens.render,
    "proxy": UsdGeom.Tokens.proxy,
}
PROXY_POST_FIX = "_&&_proxy"
SKEL_ROOT_NAME = "SkelRoot"
WORLD_ROOT_PATH = "/World"


def sanitize_name(name):
    sanitized = "".join(char if char.isalnum() or char == "_" else "_" for char in name)
    if sanitized[:1].isdigit():
        sanitized = f"_{sanitized}"
    return sanitized


def set_stage_metrics(stage, meter_per_unit, up_axis):
    """
    every output file gets both values: USD only reads them from the root layer and never
    rescales or rotates data that comes from a layer with different values, so a file
    without them is read with the fallbacks (Y up, centimetres) when it's opened on its own
    """
    UsdGeom.SetStageMetersPerUnit(stage, meter_per_unit)
    UsdGeom.SetStageUpAxis(stage, up_axis)


def define_world_groups(stage, collection_path):
    """
    defines /World/<collection path> as group Xforms and returns the last path.
    Instanced assets are components, and a component can't contain models,
    so every prim above them is a group to keep the model hierarchy valid
    """
    group_path = Sdf.Path(WORLD_ROOT_PATH)
    for part in filter(None, collection_path.split("/")):
        group_path = group_path.AppendChild(sanitize_name(part))
        if not stage.GetPrimAtPath(group_path):
            UsdGeom.Xform.Define(stage, group_path).GetPrim().SetKind(Kind.Tokens.group)
    return group_path


def unique_child_path(stage, parent_path, name):
    path = parent_path.AppendChild(name)
    index = 1
    while stage.GetPrimAtPath(path):
        path = parent_path.AppendChild(f"{name}_{index:03d}")
        index += 1
    return path


def split_variant(name):
    """splits "set{VARIANT_SEPARATOR}variant" into (set_name, variant_name); (None, name) otherwise"""
    parts = name.split(VARIANT_SEPARATOR)
    if len(parts) > 1:
        return parts[0], parts[-1]
    return None, name


def is_lod_set(variant_set_name):
    return variant_set_name.lower() == LOD_VARIANT_SET


def lod_purpose(variant_name):
    return LOD_PURPOSES.get(variant_name.lower(), UsdGeom.Tokens.guide)


def skel_root_path(asset_name):
    return f"/{sanitize_name(asset_name)}/{SKEL_ROOT_NAME}"


def asset_root_path(asset_name, has_skeleton=False):
    if has_skeleton:
        root = skel_root_path(asset_name)
    else:
        root = f"/{sanitize_name(asset_name)}"
    return root


def geom_scope_path(asset_name, has_skeleton=False):
    return f"{asset_root_path(asset_name, has_skeleton)}/Geom"


def looks_scope_path(asset_name, has_skeleton=False):
    return f"{asset_root_path(asset_name, has_skeleton)}/Looks"


def armature_scope_path(asset_name, has_skeleton=False):
    return f"{asset_root_path(asset_name, has_skeleton)}/Rig"


def joints_scope_path(asset_name):
    return f"/{sanitize_name(asset_name)}/Joints"


def local_skeleton_path(asset_name, skeleton_path):
    """
    per-variant mesh files get referenced into SkelRoot with defaultPrim remapping, which
    prefixes any relationship target under '/{asset}' with '/{asset}/SkelRoot' automatically -
    so a skeleton rel authored inside such a file must drop the SkelRoot segment once here,
    or the remap doubles it into a dangling '/{asset}/SkelRoot/SkelRoot/...' path
    """
    root = skel_root_path(asset_name)
    if skeleton_path.startswith(root):
        return f"/{sanitize_name(asset_name)}{skeleton_path[len(root):]}"
    return skeleton_path


def mesh_prim_path(asset_name, asset_outliner_path, outliner_path, has_skeleton=False):
    """
    map mesh outliner path to USD and strip autogenerated proxy suffixes
    """
    relative = outliner_path[len(asset_outliner_path):].strip("/")
    relative = relative.replace(PROXY_POST_FIX, "")
    parts = []
    for part in relative.split("/"):
        if not part:
            continue
        set_name, variant_name = split_variant(part)
        if set_name is None:
            parts.append(sanitize_name(part))
        elif is_lod_set(set_name):
            parts.append(lod_purpose(variant_name))

    prim_path = "/".join([geom_scope_path(asset_name, has_skeleton)] + parts)
    return prim_path


def base_material_name(material_name):
    return material_name.split(VARIANT_SEPARATOR)[0]


def material_prim_name(material_name):
    set_name, variant_name = split_variant(material_name)
    if set_name is None:
        return sanitize_name(material_name)
    return f"{sanitize_name(set_name)}_{sanitize_name(variant_name)}"


def matrix_to_gf(matrix_world):
    transposed = matrix_world.transposed()
    return Gf.Matrix4d(*[component for row in transposed for component in row])


def scaled_matrix_to_gf(matrix_world, scale):
    """
    matrix_to_gf, but with the translation scaled - the linear (rotation/scale) part is left
    untouched so applying `scale` here matches scaling point positions directly in local space
    """
    matrix = matrix_to_gf(matrix_world)
    matrix.SetTranslateOnly(matrix.ExtractTranslation() * scale)
    return matrix


def bone_ancestors(bone):
    ancestors = []
    current = bone.parent
    while current is not None:
        ancestors.append(current)
        current = current.parent
    return ancestors


def find_armature_modifier(mesh_obj, armature_objects):
    for modifier in mesh_obj.modifiers:
        if modifier.type == "ARMATURE" and modifier.object in armature_objects:
            return modifier
    return None
